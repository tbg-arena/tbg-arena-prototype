// '권장 세트/시간' 글 → 입력 줄 값 { amount, unit, sets }
//   "좌우 1회 x 10회" → 10회 (앞의 '1회'는 한쪽 기준이라 가장 큰 횟수를 씀) · "10회 x 5 세트" → 10회 × 5세트
//   "30초" · "1분 30초" → 시간 (1:30). 세트가 안 적혀 있으면 null (화면 기본값을 씀)
export function parsePreset(text) {
  const sets = text.match(/(\d+)\s*세트/)?.[1] ?? null;
  const min = +(text.match(/(\d+)\s*분/)?.[1] || 0), sec = +(text.match(/(\d+)\s*초/)?.[1] || 0);
  if (min || sec) return { amount: `${min}:${String(sec).padStart(2, '0')}`, unit: 'sec', sets };
  const reps = [...text.matchAll(/(\d+)\s*[회개]/g)].map((m) => +m[1]);
  return { amount: reps.length ? String(Math.max(...reps)) : '', unit: 'rep', sets };
}
